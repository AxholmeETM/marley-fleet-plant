const TABLES = ['users', 'plant', 'vehicles', 'service_records', 'plant_checks', 'vehicle_checks', 'defects', 'fuel_cards', 'fuel_entries', 'settings'];

// The SQL in this app is written with ? placeholders; Postgres wants $1, $2...
function numbered(sql) {
  let n = 0;
  let inString = false;
  let out = '';
  for (const ch of sql) {
    if (ch === "'") inString = !inString;
    out += ch === '?' && !inString ? `$${++n}` : ch;
  }
  return out;
}

let driver;
const txClient = new AsyncLocalStorage();

function connect() {
  if (process.env.DATABASE_URL) {
    const { Pool, types } = require('pg');
    types.setTypeParser(20, (v) => Number(v)); // COUNT(*) and SUM of integers
    types.setTypeParser(1700, (v) => Number(v)); // numeric
    const url = new URL(process.env.DATABASE_URL);
    const local = ['localhost', '127.0.0.1', '::1'].includes(url.hostname);
    // Supabase needs SSL. Its certificate isn't in Node's default CA list, so verify only if a CA is given.
    const ssl = local || process.env.DATABASE_SSL === 'off' ? false
      : process.env.DATABASE_CA ? { ca: process.env.DATABASE_CA } : { rejectUnauthorized: false };
    const pool = new Pool({ connectionString: process.env.DATABASE_URL, ssl, max: Number(process.env.DATABASE_POOL || 5) });
    pool.on('error', (err) => console.error('Database connection error:', err.message));
    return {
      name: 'postgres',
      query: (sql, params) => (txClient.getStore() || pool).query(sql, params),
      exec: (sql) => pool.query(sql),
      async transaction(fn) {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const result = await txClient.run(client, fn);
          await client.query('COMMIT');
          return result;
        } catch (err) {
          await client.query('ROLLBACK').catch(() => {});
          throw err;
        } finally {
          client.release();
        }
      },
      close: () => pool.end(),
    };
  }
  const { PGlite } = require('@electric-sql/pglite');
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const pg = new PGlite(path.join(DATA_DIR, 'pgdata'));
  // PGlite is a single connection, so transactions are queued one at a time.
  let queue = Promise.resolve();
  return {
    name: 'embedded',
    query: (sql, params) => (txClient.getStore() || pg).query(sql, params),
    exec: (sql) => pg.exec(sql),
    transaction(fn) {
      const run = queue.then(() => pg.transaction((tx) => txClient.run(tx, fn)));
      queue = run.catch(() => {});
      return run;
    },
    close: () => pg.close(),
  };
}

async function init() {
  driver = connect();
  await driver.exec(SCHEMA);
  // Supabase exposes the public schema through its web API. Row level security with no policies
  // shuts that door; this app connects as the database owner, which isn't affected.
  for (const t of TABLES) await driver.exec(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY`);
}
const ready = init();

async function query(sql, params) {
  await ready;
  const res = await driver.query(numbered(sql), params.map((p) => (p === undefined ? null : p)));
  return res;
}

const all = async (sql, ...params) => (await query(sql, params)).rows;
const get = async (sql, ...params) => (await query(sql, params)).rows[0];

// INSERTs return the new row's id as lastInsertRowid.
async function run(sql, ...params) {
  const insert = /^\s*INSERT\b/i.test(sql) && !/\bRETURNING\b/i.test(sql);
  const res = await query(insert ? `${sql} RETURNING *` : sql, params);
  return { changes: res.rowCount ?? res.affectedRows ?? 0, lastInsertRowid: insert && res.rows[0] ? res.rows[0].id : undefined };
}

async function exec(sql) {
  await ready;
  return driver.exec(sql);
}

async function transaction(fn) {
  await ready;
  if (txClient.getStore()) return fn();
  return driver.transaction(fn);
}

const isUniqueViolation = (err) => err && (err.code === '23505' || /unique|duplicate key/i.test(String(err.message)));

async function close() {
  await ready;
  await driver.close();
}

module.exports = { ready, all, get, run, exec, transaction, close, isUniqueViolation, TABLES, DATA_DIR, UPLOAD_DIR, driverName: () => driver && driver.name };
